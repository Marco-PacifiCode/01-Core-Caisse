CREATE TABLE "CashDeposit" (
  "id" UUID NOT NULL DEFAULT gen_random_uuid(),
  "tenantId" UUID NOT NULL,
  "actionId" UUID NOT NULL,
  "deviceId" TEXT NOT NULL,
  "deviceName" TEXT,
  "kind" TEXT NOT NULL,
  "operation" TEXT,
  "entityKey" TEXT,
  "payload" JSONB NOT NULL,
  "dependsOn" JSONB NOT NULL DEFAULT '[]'::jsonb,
  "payloadHash" TEXT NOT NULL,
  "clientCreatedAt" TIMESTAMPTZ(3),
  "clientState" TEXT,
  "clientErrorCode" TEXT,
  "receivedAt" TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  "lastSeenAt" TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  "status" TEXT NOT NULL DEFAULT 'PENDING',
  "appliedAt" TIMESTAMPTZ(3),
  "conflictCount" INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT "CashDeposit_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "CashDeposit_status_check" CHECK ("status" IN ('PENDING', 'APPLIED')),
  CONSTRAINT "CashDeposit_payload_object_check" CHECK (jsonb_typeof("payload") = 'object'),
  CONSTRAINT "CashDeposit_dependsOn_strings_check" CHECK (jsonb_typeof("dependsOn") = 'array' AND NOT jsonb_path_exists("dependsOn", '$[*] ? (@.type() != "string")')),
  CONSTRAINT "CashDeposit_kind_length_check" CHECK (char_length("kind") <= 40),
  CONSTRAINT "CashDeposit_entityKey_length_check" CHECK ("entityKey" IS NULL OR char_length("entityKey") <= 300),
  CONSTRAINT "CashDeposit_tenantId_actionId_key" UNIQUE ("tenantId", "actionId")
);
CREATE INDEX "CashDeposit_tenantId_status_receivedAt_idx" ON "CashDeposit"("tenantId", "status", "receivedAt");
